package notes;

public class ForeEach {

    public static void main(String[] args) {

        String[] cities = {"Medellin", "Sabaneta", "Envigado", "Bello", "Girardota", "Barbosa", "Copacabana", "Itagui", "La Estrella", "Caldas"};

        for (String city : cities) {
            System.out.println(city);
        }
    }
}
